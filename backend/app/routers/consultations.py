from __future__ import annotations

from datetime import date
from typing import Optional

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

from .. import models as m
from ..security import CurrentUser, get_current_user, require_doctor
from ..services.access import ensure_patient_access, resolve_patient_id
from ..services.audit import audit
from ..storage import get_repos

router = APIRouter(prefix="/api/consultations", tags=["consultations"])


class ConsultationIn(BaseModel):
    patient_id: str
    consultation_date: date = Field(default_factory=date.today)
    reason: Optional[str] = Field(default=None, max_length=200)
    notes: str = Field(min_length=3, max_length=4000)
    diagnoses: list[str] = Field(default_factory=list, max_length=10)
    follow_up: Optional[str] = Field(default=None, max_length=300)
    follow_up_date: Optional[date] = None
    prescription_items: list[m.PrescriptionItem] = Field(default_factory=list, max_length=15)


@router.post("", status_code=201, summary="Authorised doctor records a DEMO consultation (and doctor-authored proposed Rx)")
def create_consultation(body: ConsultationIn, cu: CurrentUser = Depends(require_doctor)) -> dict:
    ensure_patient_access(cu, body.patient_id, m.Scope.consultations)
    r = get_repos()
    doc = r.doctors.require(cu.user.doctor_id)  # type: ignore[arg-type]
    cid = m.new_id("con")
    rx_id = None
    if body.prescription_items:
        rx = m.Prescription(id=m.new_id("rx"), patient_id=body.patient_id, doctor_id=doc.id, doctor_name=doc.full_name,
                            consultation_id=cid, issued_on=body.consultation_date, items=body.prescription_items,
                            status="proposed_demo", authored_by="doctor")
        r.prescriptions.add(rx)
        rx_id = rx.id
        for it in body.prescription_items:
            med = m.Medication(id=m.new_id("med"), patient_id=body.patient_id, name=f"{it.name} {it.dosage}",
                               generic_name=it.name.lower().split()[0], dosage=it.dosage, frequency=it.frequency,
                               duration=it.duration, start_date=body.consultation_date, status="proposed",
                               prescribed_by=doc.full_name, prescriber_doctor_id=doc.id, source_prescription_id=rx.id,
                               notes="DEMO proposed prescription authored by the doctor in MyKshema. Not a legal "
                                     "prescription.")
            r.medications.add(med)
            r.medication_events.add(m.MedicationEvent(
                id=m.new_id("mev"), patient_id=body.patient_id, medication_id=med.id, event_date=body.consultation_date,
                event_type="proposed", description=f"{med.name} proposed by {doc.full_name} (demo)", by=doc.full_name))
    c = m.Consultation(id=cid, patient_id=body.patient_id, doctor_id=doc.id, doctor_name=doc.full_name,
                       hospital=doc.hospital, consultation_date=body.consultation_date, reason=body.reason,
                       notes=body.notes, diagnoses=[d.strip() for d in body.diagnoses if d.strip()],
                       follow_up=body.follow_up, follow_up_date=body.follow_up_date, prescription_id=rx_id,
                       created_via="doctor_portal")
    r.consultations.add(c)
    audit(cu, "consultation.created", patient_id=body.patient_id, resource_type="consultation", resource_id=c.id,
          detail=f"{len(body.prescription_items)} proposed Rx item(s)")
    return {"consultation": c.model_dump(mode="json"), "prescription_id": rx_id,
            "note": "Demo record. Prescriptions are authored by the doctor, never generated by AI."}


@router.get("")
def list_consultations(cu: CurrentUser = Depends(get_current_user), patient_id: Optional[str] = None) -> dict:
    pid = resolve_patient_id(cu, patient_id)
    ensure_patient_access(cu, pid, m.Scope.consultations)
    r = get_repos()
    cons = sorted(r.consultations.find(patient_id=pid), key=lambda c: c.consultation_date, reverse=True)
    rxs = {p.id: p for p in r.prescriptions.find(patient_id=pid)}
    docs = {d.id: d.title for d in r.documents.find(patient_id=pid)}
    out = []
    for c in cons:
        d = c.model_dump(mode="json")
        rx = rxs.get(c.prescription_id or "")
        d["prescription"] = rx.model_dump(mode="json") if rx else None
        d["source_document_title"] = docs.get(c.source_document_id or "")
        out.append(d)
    return {"consultations": out}
